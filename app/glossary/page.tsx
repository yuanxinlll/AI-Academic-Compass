"use client";

import { useState } from "react";
import { GLOSSARY, type Term } from "@/lib/glossary";
import NavBar from "../components/nav-bar";

const GROUPS: Term["group"][] = ["People", "Courses & credit", "Applying", "Money", "Status & eligibility", "Places & tools"];

export default function GlossaryPage() {
  const [q, setQ] = useState("");
  const words = q.toLowerCase().split(/\s+/).filter(Boolean);
  const shown = GLOSSARY.filter((t) => words.every((w) => `${t.term} ${t.text}`.toLowerCase().includes(w)));
  return (
    <>
      <NavBar />
      <main className="ac-page ac-narrow">
        <section className="ac-section">
          <p className="ac-eyebrow">The hidden curriculum</p>
          <h1 className="ac-h1">Campus words, explained</h1>
          <p className="ac-muted">
            Listings assume you already know what a PI is, what &ldquo;199 credit&rdquo; means, or that you can email a professor you have
            never met. Students whose parents went to college often learn this at home. Everyone else learns it here. These {GLOSSARY.length}{" "}
            definitions are written by our team, not generated by AI, and the same words are underlined on every listing.
          </p>
          <label className="ac-search ac-glossary-search">
            <svg className="ac-search-icon" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" aria-hidden="true">
              <circle cx="11" cy="11" r="7" />
              <path d="m20 20-3.5-3.5" />
            </svg>
            <input className="ac-search-input" type="search" placeholder="Look up a word, e.g. stipend" aria-label="Search campus words" value={q} onChange={(e) => setQ(e.target.value)} />
          </label>
        </section>
        {GROUPS.map((g) => {
          const items = shown.filter((t) => t.group === g);
          if (!items.length) return null;
          return (
            <section key={g} className="ac-panel-card ac-glossary-group">
              <h2>{g}</h2>
              <dl>
                {items.map((t) => (
                  <div key={t.term} id={t.term.toLowerCase().replace(/[^a-z0-9]+/g, "-")}>
                    <dt>{t.term}</dt>
                    <dd>{t.text}</dd>
                  </div>
                ))}
              </dl>
            </section>
          );
        })}
        {!shown.length ? <p className="ac-empty">No word matches &ldquo;{q}&rdquo;.</p> : null}
        <p className="ac-fineprint">
          Something missing or unclear? Tell a reviewer from any listing with &ldquo;Report a problem&rdquo;.
        </p>
      </main>
    </>
  );
}
